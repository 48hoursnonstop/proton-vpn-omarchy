var pluralRules = {}

function own(object, key) {
  return object !== null && object !== undefined &&
    Object.prototype.hasOwnProperty.call(object, key)
}

function normalizedTag(value) {
  return String(value || "").trim().replace(/_/g, "-").toLowerCase()
}

function normalizeLocale(value) {
  var candidate = normalizedTag(value)
  var codes = Object.keys(localeDefinitions)
  for (var index = 0; index < codes.length; ++index) {
    var code = codes[index]
    var definition = localeDefinitions[code]
    if (normalizedTag(definition.code) === candidate) return code
    var aliases = Array.isArray(definition.aliases) ? definition.aliases : []
    for (var aliasIndex = 0; aliasIndex < aliases.length; ++aliasIndex) {
      if (normalizedTag(aliases[aliasIndex]) === candidate) return code
    }
  }
  var primary = candidate.split("-")[0]
  return own(localeDefinitions, primary) ? primary : fallbackLocale
}

function localeOptions() {
  return Object.keys(localeDefinitions).map(function(code) {
    var definition = localeDefinitions[code]
    return {
      value: String(definition.code || code),
      label: String(definition.nativeName || code),
      iconName: "language"
    }
  })
}

function registerLocale(definition, catalog, pluralRule) {
  var declaredCode = normalizedTag(definition && definition.code)
  var code = normalizedTag(
    definition && definition.key ? definition.key : declaredCode.split("-")[0]
  )
  if (!/^[a-z]{2,8}$/.test(code) ||
      !/^[a-z]{2,8}(-[a-z0-9]{1,8})*$/.test(declaredCode) ||
      !definition.nativeName || !catalog ||
      !sameCatalogShape(catalogs[fallbackLocale], catalog))
    throw new Error("Invalid locale registration")
  localeDefinitions[code] = {
    code: String(definition.code),
    nativeName: String(definition.nativeName),
    aliases: Array.isArray(definition.aliases) ? definition.aliases.slice(0) : []
  }
  catalogs[code] = catalog
  if (typeof pluralRule === "function") pluralRules[code] = pluralRule
}

function sameCatalogShape(reference, candidate) {
  if (!reference || !candidate || typeof reference !== "object" ||
      typeof candidate !== "object") return false
  var sections = Object.keys(reference)
  for (var sectionIndex = 0; sectionIndex < sections.length; ++sectionIndex) {
    var section = sections[sectionIndex]
    if (!own(candidate, section) || typeof candidate[section] !== "object")
      return false
    var keys = Object.keys(reference[section])
    for (var keyIndex = 0; keyIndex < keys.length; ++keyIndex) {
      if (!own(candidate[section], keys[keyIndex])) return false
    }
  }
  return true
}

function catalogsAreComplete() {
  if (!own(catalogs, fallbackLocale)) return false
  var codes = Object.keys(localeDefinitions)
  for (var index = 0; index < codes.length; ++index) {
    if (!own(catalogs, codes[index]) ||
        !sameCatalogShape(catalogs[fallbackLocale], catalogs[codes[index]]))
      return false
  }
  return true
}

function pluralCategory(locale, count) {
  var code = normalizeLocale(locale)
  if (typeof pluralRules[code] === "function")
    return String(pluralRules[code](Number(count)))
  return Number(count) === 1 ? "one" : "other"
}

function selectValue(locale, value, count) {
  if (value === null || value === undefined) return undefined
  if (typeof value !== "object") return String(value)
  var category = pluralCategory(locale, count)
  if (own(value, category)) return String(value[category])
  if (own(value, "other")) return String(value.other)
  return undefined
}

function interpolate(value, replacements) {
  var output = String(value)
  var values = replacements || {}
  return output.replace(/\{([A-Za-z0-9_]+)\}/g, function(match, key) {
    return own(values, key) ? String(values[key]) : match
  })
}

function translate(locale, section, key, replacements, count, fallback) {
  var code = normalizeLocale(locale)
  var value
  if (own(catalogs, code) && own(catalogs[code], section) &&
      own(catalogs[code][section], key))
    value = catalogs[code][section][key]
  if (value === undefined && own(catalogs, fallbackLocale) &&
      own(catalogs[fallbackLocale], section) &&
      own(catalogs[fallbackLocale][section], key))
    value = catalogs[fallbackLocale][section][key]
  value = selectValue(code, value, count)
  if (value === undefined) value = fallback === undefined ? key : fallback
  return interpolate(value, replacements)
}
